// Courier-Bold is fixed-pitch: every WinAnsi byte advances 600 units.
const COURIER_BOLD = 600;

// WinAnsi bytes 0x80-0x9F are printable extras, not the C1 controls: the
// Unicode char that encodes to each byte. Bytes 0x20-0x7E and 0xA0-0xFF map
// to the same code point; anything else becomes "?" (0x3F), so unencodable
// input (emoji, arrows) can never corrupt a content stream.
const EXTRAS: Record<string, number> = {
  "€": 0x80,
  "‚": 0x82,
  "ƒ": 0x83,
  "„": 0x84,
  "…": 0x85,
  "†": 0x86,
  "‡": 0x87,
  "ˆ": 0x88,
  "‰": 0x89,
  "Š": 0x8a,
  "‹": 0x8b,
  "Œ": 0x8c,
  "Ž": 0x8e,
  "‘": 0x91,
  "’": 0x92,
  "“": 0x93,
  "”": 0x94,
  "•": 0x95,
  "–": 0x96,
  "—": 0x97,
  "˜": 0x98,
  "™": 0x99,
  "š": 0x9a,
  "›": 0x9b,
  "œ": 0x9c,
  "ž": 0x9e,
  "Ÿ": 0x9f,
};

export type PdfFontName = "regular" | "bold" | "italic" | "mono";

// winAnsiByte: the single content-stream byte for one char.
export function winAnsiByte(ch: string): number {
  const extra = EXTRAS[ch];
  if (extra !== undefined) return extra;
  const code = ch.codePointAt(0) ?? 0x3f;
  if (code === 0xa0 || (code >= 0xa1 && code <= 0xff)) return code;
  if (code >= 0x20 && code <= 0x7e) return code;
  return 0x3f;
}

// encodeWinAnsi: text to the raw bytes a content stream carries.
export function encodeWinAnsi(text: string): Uint8Array {
  const out = new Uint8Array([...text].length);
  let i = 0;
  for (const ch of text) out[i++] = winAnsiByte(ch);
  return out;
}

// advanceOf: AFM units for one WinAnsi byte in the given face.
function advanceOf(byte: number, font: PdfFontName): number {
  if (font === "mono") return COURIER_BOLD;
  const table = font === "bold" ? HELV_BOLD : HELV;
  return table[byte] ?? 500;
}

// textWidth: the width of already-sanitized text in points.
export function textWidth(
  text: string,
  font: PdfFontName,
  size: number,
): number {
  const bytes = encodeWinAnsi(text);
  let total = 0;
  for (const b of bytes) total += advanceOf(b, font);
  return (total * size) / 1000;
}

// wrapText: greedy word wrap inside maxWidth points. Words longer than the
// column break anywhere (the HTML report wraps with overflow-wrap:anywhere),
// so one long token can never push its column wider than its share.
export function wrapText(
  text: string,
  font: PdfFontName,
  size: number,
  maxWidth: number,
): string[] {
  if (text === "") return [""];
  const lines: string[] = [];
  const space = textWidth(" ", font, size);
  // breakWord: emits a word that alone overflows, chunk by chunk.
  const breakWord = (word: string): { tail: string; width: number } => {
    let chunk = "";
    let chunkWidth = 0;
    for (const ch of word) {
      const w = textWidth(ch, font, size);
      if (chunk !== "" && chunkWidth + w > maxWidth) {
        lines.push(chunk);
        chunk = "";
        chunkWidth = 0;
      }
      chunk += ch;
      chunkWidth += w;
    }
    return { tail: chunk, width: chunkWidth };
  };
  for (const paragraph of text.split("\n")) {
    let line = "";
    let width = 0;
    for (const word of paragraph.split(" ")) {
      const wordWidth = textWidth(word, font, size);
      if (line === "") {
        if (wordWidth <= maxWidth) {
          line = word;
          width = wordWidth;
        } else {
          const broken = breakWord(word);
          line = broken.tail;
          width = broken.width;
        }
      } else if (width + space + wordWidth <= maxWidth) {
        line += " " + word;
        width += space + wordWidth;
      } else {
        lines.push(line);
        if (wordWidth <= maxWidth) {
          line = word;
          width = wordWidth;
        } else {
          const broken = breakWord(word);
          line = broken.tail;
          width = broken.width;
        }
      }
    }
    lines.push(line);
  }
  return lines;
}
